function section({ id, kicker, title, lead, content, cls = "", reveal = true }) {
  const hd =
    kicker || title || lead
      ? `  <div class="section__hd${reveal ? " reveal" : ""}">
${kicker ? `    <span class="kicker">${kicker}</span>\n` : ""}${title ? `    <h2 class="section__title">${title}</h2>\n` : ""}${lead ? `    <p class="section__lead">${lead}</p>\n` : ""}  </div>
`
      : "";
  return `<section class="section${cls ? " " + cls : ""}"${id ? ` id="${id}"` : ""}>
  <div class="wrap">
${hd}${content}
  </div>
</section>`;
}

function kvTable(rows, { caption = "", cls = "" } = {}) {
  return `<div class="tbl-scroll">
  <table class="tbl tbl--kv${cls ? " " + cls : ""}">
${caption ? `    <caption>${caption}</caption>\n` : ""}    <tbody>
${rows
  .map(([k, v, note]) => {
    const extra = note ? `<br><span class="card__meta" style="margin:0">${note}</span>` : "";
    return `      <tr><th scope="row">${k}</th><td>${v}${extra}</td></tr>`;
  })
  .join("\n")}
    </tbody>
  </table>
</div>`;
}

