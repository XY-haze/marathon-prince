/* ---- 2. 手写静态资源 → dist/assets/ ---- */
const ASSETS = [
  [join(SRC, "style.css"), join(DIST, "assets", "css", "style.css"), "assets/css/style.css"],
  [join(SRC, "site.js"), join(DIST, "assets", "js", "site.js"), "assets/js/site.js"],
];
for (const [from, to, label] of ASSETS) {
  const buf = readFileSync(from);
  writeFileSync(to, buf);
  console.log(`  ✓ ${label.padEnd(24)} ${(buf.length / 1024).toFixed(1)} KB`);
}

