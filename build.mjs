console.log("  ✓ .nojekyll / robots.txt");

/* ---- 5. 离线单文件版 → dist-standalone/ ---- */
const css = readFileSync(join(SRC, "style.css"), "utf8");
const js = readFileSync(join(SRC, "site.js"), "utf8");
const dataUri = (svg) => `data:image/svg+xml;base64,${Buffer.from(svg, "utf8").toString("base64")}`;

console.log("\n▸ dist-standalone/（离线单文件版，CSS / JS / 插画全部内联）");
for (const [file, html] of Object.entries(PAGES)) {
  let out = html
    .replace(
      '<link rel="stylesheet" href="assets/css/style.css">',
      `<style>\n${css}\n</style>`
    )
    .replace(
      '<script src="assets/js/site.js" defer></script>',
      `<script>\n${js}\n</script>`
    )
    .replace(/assets\/img\/([a-z0-9-]+)\.svg/g, (m, name) =>
      ART[`${name}.svg`] ? dataUri(ART[`${name}.svg`]) : m
    );

  const leftovers = [...out.matchAll(/assets\//g)].length;
  if (leftovers) {
    console.log(`  ! ${file} 仍有 ${leftovers} 处 assets/ 引用未内联`);
    process.exitCode = 1;
  }
  writeFileSync(join(STANDALONE, file), out, "utf8");
  console.log(`  ✓ ${file.padEnd(18)} ${(Buffer.byteLength(out, "utf8") / 1024).toFixed(1)} KB`);
}

